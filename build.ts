// Prepares docs/ (the GitHub Pages site) so the demo runs fully in the browser:
//   docs/analyze.js  <- impact/analyze.ts with types stripped (same code the tests cover)
//   docs/specs.js    <- every specs/*.yaml, for the preset buttons
//   docs/oasdiff.wasm + wasm_exec.js  <- real oasdiff compiled to WebAssembly (only with --wasm; needs Go)
// Usage: node build.ts [--wasm]
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, copyFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

const here = (p: string) => new URL(p, import.meta.url);

writeFileSync(here('./docs/analyze.js'),
  '// GENERATED by build.ts from impact/analyze.ts. Do not edit.\n' +
  stripTypeScriptTypes(readFileSync(here('./impact/analyze.ts'), 'utf8')));

const specs = Object.fromEntries(readdirSync(here('./specs/')).filter(f => f.endsWith('.yaml'))
  .map(f => [f, readFileSync(here(`./specs/${f}`), 'utf8')]));
const { usage } = JSON.parse(readFileSync(here('./impact/usage.json'), 'utf8'));
writeFileSync(here('./docs/specs.js'), '// GENERATED by build.ts from specs/ and impact/usage.json. Do not edit.\n' +
  `export const SPECS = ${JSON.stringify(specs, null, 2)};\nexport const USAGE = ${JSON.stringify(usage, null, 2)};\n`);

if (process.argv.includes('--wasm')) {
  const r = spawnSync('go', ['build', '-buildvcs=false', '-ldflags=-s -w', '-o', '../docs/oasdiff.wasm', '.'],
    { cwd: here('./wasm/'), stdio: 'inherit', env: { ...process.env, GOOS: 'js', GOARCH: 'wasm' } });
  if (r.status !== 0) process.exit(r.status ?? 1);
  const goroot = spawnSync('go', ['env', 'GOROOT'], { encoding: 'utf8' }).stdout.trim();
  copyFileSync(`${goroot}/lib/wasm/wasm_exec.js`, here('./docs/wasm_exec.js'));
}
console.log(`docs/ built: analyze.js, specs.js (${Object.keys(specs).length} specs)${process.argv.includes('--wasm') ? ', oasdiff.wasm' : ''}`);
